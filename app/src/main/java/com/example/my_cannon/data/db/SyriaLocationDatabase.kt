    fun search(query: String): List<SearchResult> {
        val normQuery = normalizeArabic(query)
        if (normQuery.length < 2) return emptyList()

        val stripAl = { s: String -> if (s.startsWith("ال") && s.length > 2) s.substring(2) else s }
        val queryNoAl = stripAl(normQuery)
        val queryTokens = normQuery.split(" ").filter { it.isNotEmpty() }

        val matched = places.mapNotNull { place ->
            val normName = normalizeArabic(place.nameAr)
            val normDistrict = normalizeArabic(place.districtOrArea)
            val normProvince = normalizeArabic(place.province)
            val nameNoAl = stripAl(normName)

            var score = 0

            if (normName == normQuery || nameNoAl == queryNoAl) {
                score += 100
            } else if (normName.startsWith(normQuery) || nameNoAl.startsWith(queryNoAl)) {
                score += 80
            } else if (normName.contains(normQuery) || nameNoAl.contains(queryNoAl)) {
                score += 60
            } else if (normDistrict.contains(normQuery) || normDistrict.contains(queryNoAl)) {
                score += 40
            } else if (normProvince.contains(normQuery) || normProvince.contains(queryNoAl)) {
                score += 20
            } else {
                val allTokensMatch = queryTokens.all { token ->
                    val tokenNoAl = stripAl(token)
                    normName.contains(token) || nameNoAl.contains(tokenNoAl) || normDistrict.contains(token)
                }
                if (allTokensMatch && queryTokens.isNotEmpty()) {
                    score += 30
                }
            }

            if (score > 0) {
                val fullAddress = "${place.category} ${place.nameAr} - ${place.districtOrArea}"
                val result = SearchResult(
                    name = place.nameAr,
                    fullAddress = fullAddress,
                    province = place.province,
                    point = Point.fromLngLat(place.lng, place.lat)
                )
                Pair(score, result)
            } else null
        }

        return matched.sortedByDescending { it.first }
            .map { it.second }
            .distinctBy { Pair(it.name, it.province) }
            .take(20)
    }

    private fun normalizeArabic(text: String): String {
        return text.trim()
            .replace(Regex("[\u064B-\u0652]"), "")
            .replace("أ", "ا")
            .replace("إ", "ا")
            .replace("آ", "ا")
            .replace("ى", "ي")
            .replace("ؤ", "و")
            .replace("ئ", "ي")
            .replace("ة", "ه")
            .lowercase()
    }
